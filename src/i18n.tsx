// ============ 星期輔助 ============
const ZH_JS_SHORT = ['日', '一', '二', '三', '四', '五', '六'];   // index = getDay()
const EN_JS_SHORT = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
const ZH_JS_FULL = ['週日', '週一', '週二', '週三', '週四', '週五', '週六'];
const EN_JS_FULL = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];

/** JS 慣例 dow（0=週日..6=週六）→ 短名 */
export function jsDayShort(lang: Lang, dow: number): string {
  return (lang === 'zh' ? ZH_JS_SHORT : EN_JS_SHORT)[((dow % 7) + 7) % 7];
}

/** JS 慣例 dow → 全名（週一 / Monday） */
export function jsDayLong(lang: Lang, dow: number): string {
  return (lang === 'zh' ? ZH_JS_FULL : EN_JS_FULL)[((dow % 7) + 7) % 7];
}

/** App 慣例 dow（1=週一..7=週日）→ 短名（一 / Mon） */
export function appDayShort(lang: Lang, dow: number): string {
  return jsDayShort(lang, dow % 7); // 7→0(日) ✓, 1→1(一) ✓
}

/** App 慣例 dow（1=週一..7=週日）→ 全名（周一 / Monday） */
export function appDayLong(lang: Lang, dow: number): string {
  return jsDayLong(lang, dow % 7);
}

