// ============ Context ============
interface LangCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  /** 學校名（默認 CITYUHK，我的頁可改成自己的學校，僅英文/數字） */
  school: string;
  setSchool: (s: string) => void;
  t: (key: TKey, params?: Record<string, string | number | undefined>) => string;
}

const SCHOOL_KEY = 'school_name';

const LangContext = createContext<LangCtx>({
  lang: 'zh',
  setLang: () => {},
  school: 'CITYUHK',
  setSchool: () => {},
  t: (key) => dict.zh[key],
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      return localStorage.getItem(LS_KEY) === 'en' ? 'en' : 'zh';
    } catch {
      return 'zh';
    }
  });
  const [school, setSchoolState] = useState<string>(() => {
    try {
      const s = localStorage.getItem(SCHOOL_KEY);
      // 只接受英文字母/數字/空格（學校縮寫，如 HIT / HKU / UCL）
      return s && /^[A-Za-z0-9 ]+$/.test(s) ? s : 'CITYUHK';
    } catch {
      return 'CITYUHK';
    }
  });

  const setLang = (l: Lang) => {
    try { localStorage.setItem(LS_KEY, l); } catch { /* ignore */ }
    setLangState(l);
  };

  const setSchool = (s: string) => {
    const v = s.trim() || 'CITYUHK';
    try { localStorage.setItem(SCHOOL_KEY, v); } catch { /* ignore */ }
    setSchoolState(v);
  };

  const t = (key: TKey, params?: Record<string, string | number | undefined>): string => {
    let s = dict[lang][key] ?? dict.zh[key] ?? key;
    // {school} 全局注入：詞條裡寫 {school} 即可，無需每處傳參
    s = s.split('{school}').join(school);
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        s = s.split(`{${k}}`).join(v === undefined || v === null ? '-' : String(v));
      }
    }
    return s;
  };

  return <LangContext.Provider value={{ lang, setLang, school, setSchool, t }}>{children}</LangContext.Provider>;
}

export function useLang(): LangCtx {
  return useContext(LangContext);
}
